import { PrismaClient } from "@prisma/client";

const globalForPrisma = globalThis;

export const prisma =
  globalForPrisma.prisma ??
  new PrismaClient({
    log: process.env.PRISMA_LOG_QUERIES === "1" ? ["query", "error", "warn"] : ["error"],
  });

if (process.env.NODE_ENV !== "production") globalForPrisma.prisma = prisma;

export function intParam(searchParams, name, fallback = 0, min = null, max = null) {
  const raw = searchParams.get(name);
  let value = Number.parseInt(raw ?? fallback, 10);
  if (Number.isNaN(value)) value = fallback;
  if (min !== null) value = Math.max(min, value);
  if (max !== null) value = Math.min(max, value);
  return value;
}

export function textParam(searchParams, name) {
  return (searchParams.get(name) ?? "").trim();
}

export function sqlString(value) {
  return `'${String(value ?? "").replaceAll("'", "''")}'`;
}

export function like(value) {
  return sqlString(`%${String(value ?? "").toLowerCase()}%`);
}

function jsonValue(value) {
  if (typeof value === "bigint") {
    const asNumber = Number(value);
    return Number.isSafeInteger(asNumber) ? asNumber : value.toString();
  }
  if (value instanceof Date) return value.toISOString();
  if (value && value.constructor?.name === "Decimal") return Number(value.toString());
  if (Array.isArray(value)) return value.map(jsonValue);
  if (value && typeof value === "object") {
    if (
      Object.keys(value).every((key) => ["s", "e", "d"].includes(key)) &&
      Array.isArray(value.d) &&
      typeof value.s === "number" &&
      typeof value.e === "number"
    ) {
      return Number(`${value.s < 0 ? "-" : ""}${value.d.join("")}`) / 10 ** Math.max(0, value.d.join("").length - value.e - 1);
    }
    return Object.fromEntries(Object.entries(value).map(([key, entry]) => [key, jsonValue(entry)]));
  }
  return value;
}

export async function runJson(sql) {
  const rows = await prisma.$queryRawUnsafe(sql);
  return jsonValue(rows);
}

export async function execSql(sql) {
  const statements = sql
    .split(";")
    .map((statement) => statement.trim())
    .filter(Boolean);
  for (const statement of statements) {
    await prisma.$executeRawUnsafe(statement);
  }
}

export async function one(sql, fallback = {}) {
  const rows = await runJson(sql);
  return rows[0] ?? fallback;
}

export async function ensurePageFavoritesTable() {
  await execSql(`
    CREATE TABLE IF NOT EXISTS page_favorites (
      page_id TEXT PRIMARY KEY REFERENCES pages(page_id),
      note TEXT,
      created_at TIMESTAMP NOT NULL DEFAULT now(),
      updated_at TIMESTAMP NOT NULL DEFAULT now()
    );
    CREATE INDEX IF NOT EXISTS idx_page_favorites_page_id ON page_favorites(page_id);
  `);
}

export async function ensurePageLibrarySyncsTable() {
  await execSql(`
    CREATE TABLE IF NOT EXISTS page_library_syncs (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      page_id TEXT NOT NULL,
      page_name TEXT,
      max_items INTEGER NOT NULL,
      items_seen INTEGER NOT NULL DEFAULT 0,
      items_inserted INTEGER NOT NULL DEFAULT 0,
      items_updated INTEGER NOT NULL DEFAULT 0,
      captured_total_after INTEGER NOT NULL DEFAULT 0,
      actor_run_id TEXT,
      dataset_id TEXT,
      status TEXT NOT NULL DEFAULT 'ok',
      error TEXT,
      synced_at TIMESTAMP NOT NULL DEFAULT now()
    );
    CREATE INDEX IF NOT EXISTS idx_page_library_syncs_page_id ON page_library_syncs(page_id);
    CREATE INDEX IF NOT EXISTS idx_page_library_syncs_page_id_id ON page_library_syncs(page_id, id DESC);
  `);
}

export async function ensurePageStatsTable() {
  await execSql(`
    CREATE TABLE IF NOT EXISTS page_stats (
      page_id TEXT PRIMARY KEY REFERENCES pages(page_id),
      page_name TEXT,
      page_like_count BIGINT,
      ads_count INTEGER NOT NULL DEFAULT 0,
      active_ads INTEGER NOT NULL DEFAULT 0,
      max_active_days INTEGER,
      avg_active_days DOUBLE PRECISION,
      first_seen_at TIMESTAMP,
      last_seen_at TIMESTAMP,
      updated_at TIMESTAMP NOT NULL DEFAULT now()
    );
    CREATE INDEX IF NOT EXISTS idx_page_stats_active_ads ON page_stats(active_ads DESC);
    CREATE INDEX IF NOT EXISTS idx_page_stats_ads_count ON page_stats(ads_count DESC);
    CREATE INDEX IF NOT EXISTS idx_page_stats_max_active_days ON page_stats(max_active_days DESC);
    CREATE INDEX IF NOT EXISTS idx_page_stats_avg_active_days ON page_stats(avg_active_days DESC);
    CREATE INDEX IF NOT EXISTS idx_page_stats_likes ON page_stats(page_like_count DESC);
  `);
}

export async function tableExists(name) {
  const row = await one(`
    SELECT 1 AS ok
    FROM information_schema.tables
    WHERE table_schema = 'public'
      AND table_name = ${sqlString(name)}
    LIMIT 1
  `, null);
  return Boolean(row?.ok);
}

export function domainExpr(alias = null) {
  return alias ? `${alias}.link_domain` : "link_domain";
}
